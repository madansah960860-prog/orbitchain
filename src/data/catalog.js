/* ------------------------------ helpers ------------------------------ */

export const bySlug = (slug) => products.find((x) => x.slug === slug)
export const byId = (id) => products.find((x) => x.id === id)
export const byCategory = (cat) => products.filter((x) => x.category === cat)
export const featured = () => products.filter((x) => x.featured)

export const categoryName = (id) => categories.find((c) => c.id === id)?.name ?? id

/** Every distinct device family mentioned in any `fit` array. */
export const deviceFamilies = ['iPhone', 'iPad', 'Apple Watch', 'Mac', 'AirPods']

export const fitsFamily = (product, family) =>
  product.fit.some((f) => f.toLowerCase().includes(family.toLowerCase()))

export const priceBands = [
  { id: 'u25', label: 'Under $25', test: (x) => x.price < 25 },
  { id: '25-50', label: '$25 – $50', test: (x) => x.price >= 25 && x.price < 50 },
  { id: '50-100', label: '$50 – $100', test: (x) => x.price >= 50 && x.price < 100 },
  { id: 'o100', label: '$100 and up', test: (x) => x.price >= 100 },
]

export function searchProducts(query) {
  const q = query.trim().toLowerCase()
  if (!q) return []
  const terms = q.split(/\s+/)
  return products
    .map((prod) => {
      const haystack = [
        prod.name,
        prod.brand,
        prod.blurb,
        prod.sku,
        categoryName(prod.category),
        ...prod.fit,
        ...Object.values(prod.specs ?? {}),
      ]
        .join(' ')
        .toLowerCase()
      const score = terms.reduce((acc, t) => {
        if (prod.name.toLowerCase().includes(t)) return acc + 3
        if (haystack.includes(t)) return acc + 1
        return acc
      }, 0)
      return { prod, score }
    })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score)
    .map((x) => x.prod)
}
